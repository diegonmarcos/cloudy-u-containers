#!/usr/bin/env node
// gen-security-testing-allowlist.mjs — emit _shared/security-testing-allowlist.json
// from the fleet's OWN topology: owner domain + mesh suffixes from
// _shared/fleet-addressing.json, VM public IPs from config.json (the fleet
// topology). The private WireGuard CIDRs + loopback are constants of the mesh.
// This keeps the allowlist DATA derived from the single routing/topology SoT —
// a new VM or domain re-runs the generator, never hand-edits the target list.
//
// Usage: gen-security-testing-allowlist.mjs [--check]
//   (no arg) writes the JSON; --check fails if the committed JSON is stale.
// config.json is read from the fleet root when present (CI: infra/ root with
// a_solutions/_shared here); standalone it falls back to the committed IPs.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const addressing = JSON.parse(readFileSync(join(here, "fleet-addressing.json"), "utf8"));
const OUT = join(here, "security-testing-allowlist.json");

// Owner domain: the public zone the whole fleet lives under. Taken from the
// mesh namespace suffix in fleet-addressing.json (".mesh.diegonmarcos.com").
const meshSuffix = (addressing.mesh?.private_suffixes || []).find((s) => s.endsWith(".diegonmarcos.com")) || ".mesh.diegonmarcos.com";
const baseDomain = meshSuffix.split(".").slice(-2).join("."); // diegonmarcos.com

// VM public IPs from config.json (fleet topology) if reachable, else keep prior.
const roots = [resolve(here, "../../config.json"), resolve(here, "../../../config.json"), "/home/user/cloudy-t-infra/config.json"];
let vmIps = {};
for (const p of roots) {
  if (existsSync(p)) {
    try {
      const cfg = JSON.parse(readFileSync(p, "utf8"));
      for (const [id, v] of Object.entries(cfg.vms || {})) {
        const ip = v.public_ip || v.ip;
        if (ip && /^\d+\.\d+\.\d+\.\d+$/.test(ip)) vmIps[ip] = id;
      }
      break;
    } catch { /* ignore */ }
  }
}
if (!Object.keys(vmIps).length && existsSync(OUT)) {
  vmIps = JSON.parse(readFileSync(OUT, "utf8"))._ip_source || {};
}

const doc = {
  _doc: "THE declared target allowlist for the owner's security-testing containers (infra-sec_steel-browser, infra-sec_zap). DATA, not code. Every Steel/ZAP MCP tool resolves the target host of a request and REFUSES + logs it unless it matches one of these rules; ZAP mirrors the same list as its context/scope. Scope: the owner's OWN fleet only — *.diegonmarcos.com, the mesh namespace, the WireGuard CIDRs, loopback, and the fleet VM public IPs. GENERATED by _shared/gen-security-testing-allowlist.mjs from _shared/fleet-addressing.json (domains + mesh suffixes) and config.json (VM public IPs). Do not edit by hand; change the source and re-run the generator (--check in CI). Guard: _shared/test-security-testing-allowlist.mjs.",
  _generated_by: "_shared/gen-security-testing-allowlist.mjs",
  schema: "security-testing-allowlist/v1",
  default: "deny",
  rules: {
    domain_suffixes: [baseDomain, "." + baseDomain],
    mesh_suffixes: [".mesh." + baseDomain, ".home.arpa", ".internal"],
    cidrs: ["127.0.0.0/8", "::1/128", "10.0.0.0/24", "10.1.0.0/24", "fd0c:1d00::/64", "fd0c:1d01::/64"],
    exact_ips: Object.keys(vmIps).sort(),
  },
  _ip_source: vmIps,
};

const rendered = JSON.stringify(doc, null, 2) + "\n";
if (process.argv.includes("--check")) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (cur.trim() !== rendered.trim()) { console.error("security-testing-allowlist.json is STALE; run gen-security-testing-allowlist.mjs"); process.exit(1); }
  console.log("security-testing-allowlist.json fresh"); process.exit(0);
}
writeFileSync(OUT, rendered);
console.log("wrote", OUT, "with", doc.rules.exact_ips.length, "fleet IPs");
