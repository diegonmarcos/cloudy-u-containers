type Endpoint struct {
	Method string `json:"method"`
	Path   string `json:"path"`
	Auth   string `json:"auth"`
}

type repoDecl struct {
	Name   string `json:"name"`
	SSH    string `json:"ssh"`
	Branch string `json:"branch"`
	KeyEnv string `json:"key_env"`
}

type dataset struct {
	Builtin *string `json:"builtin"`
	Repo    string  `json:"repo"`
	Path    string  `json:"path"`
}

// Runtime is the validated runtime block.
type Runtime struct {
	BasePath     string          `json:"base_path"`
	Endpoints    []Endpoint      `json:"-"`
	RawEndpoints json.RawMessage `json:"endpoints"`
	Repos        struct {
		List          []repoDecl `json:"list"`
		SyncIntervalS float64    `json:"sync_interval_s"`
		GitTimeoutMS  float64    `json:"git_timeout_ms"`
		KnownHosts    string     `json:"known_hosts"`
	} `json:"repos"`
	Datasets     map[string]json.RawMessage `json:"datasets"`
	Autocomplete *struct {
		Repo string `json:"repo"`
		Path string `json:"path"`
	} `json:"autocomplete"`
	Files struct {
		AllowedExt  []string `json:"allowed_ext"`
		MaxBytes    float64  `json:"max_bytes"`
		DenyPath    string   `json:"deny_path"`
		DenyContent string   `json:"deny_content"`
	} `json:"files"`
	Authelia struct {
		JWKSURL            string `json:"jwks_url"`
		Issuer             string `json:"issuer"`
		RequiredScope      string `json:"required_scope"`
		JWKSCacheTTLS      int    `json:"jwks_cache_ttl_s"`
		JWKSFetchTimeoutMS int    `json:"jwks_fetch_timeout_ms"`
		Session            *struct {
			VerifyURL string   `json:"verify_url"`
			PublicURL string   `json:"public_url"`
			Users     []string `json:"users"`
			TimeoutMS int      `json:"timeout_ms"`
		} `json:"session"`
	} `json:"authelia"`
	Cors *struct {
		Origins      []string `json:"origins"`
		OriginSuffix *string  `json:"origin_suffix"`
	} `json:"cors"`

	tree *ojson.Obj
}

var (
	nameRe   = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$`)
	envRe    = regexp.MustCompile(`^[A-Z][A-Z0-9_]{2,63}$`)
	khRe     = regexp.MustCompile(`^github\.com ssh-ed25519 \S+$`)
	sshRe    = regexp.MustCompile(`^git@github\.com:[A-Za-z0-9._-]+/[A-Za-z0-9._-]+\.git$`)
	branchRe = regexp.MustCompile(`^[A-Za-z0-9._/-]{1,100}$`)
	vaultRe  = regexp.MustCompile(`(?i)vault`)
	extRe    = regexp.MustCompile(`^\.[a-z0-9]+$`)
	builtRe  = regexp.MustCompile(`^data/[A-Za-z0-9_-]+\.json$`)
	originRe = regexp.MustCompile(`^https://[^/*]+$`)
	suffixRe = regexp.MustCompile(`^\.[a-z0-9.-]+$`)
	pubRe    = regexp.MustCompile(`^https://[^/]+$`)
)

func validUTF8(s string) bool { return utf8.ValidString(s) }

// LocalPath turns a declared path into the path the server matches on (Caddy strips the base path).
func LocalPath(declared, base string) string {
	s := declared[len(base):]
	if s == "" {
		return "/"
	}
	return s
}

// LoadRuntime parses and validates a runtime block exactly like contract.mjs loadRuntime.
func LoadRuntime(data []byte) (*Runtime, error) {
	var rt Runtime
	if err := json.Unmarshal(data, &rt); err != nil {
		return nil, err
	}
	tree, err := ojson.Parse(data)
	if err != nil {
		return nil, err
	}
	rt.tree = tree.(*ojson.Obj)
	if err := json.Unmarshal(rt.RawEndpoints, &rt.Endpoints); err != nil || len(rt.Endpoints) == 0 {
		return nil, errors.New("build.json runtime.endpoints is missing or empty")
	}
	if !strings.HasPrefix(rt.BasePath, "/") {
		return nil, errors.New("build.json runtime.base_path must be an absolute path")
	}
	for _, e := range rt.Endpoints {
		if e.Method == "" || e.Path == "" || e.Auth == "" {
			return nil, fmt.Errorf("build.json runtime.endpoints entry missing method/path/auth: %+v", e)
		}
		if !strings.HasPrefix(e.Path, rt.BasePath) {
			return nil, fmt.Errorf("endpoint %s does not sit under base_path %s", e.Path, rt.BasePath)
		}
		// Only /health may be unauthenticated: a declared open route is a data leak waiting for a data file.
		if e.Auth == "none" && e.Path != rt.BasePath+"/health" {
			return nil, fmt.Errorf("endpoint %s is auth \"none\": only %s/health may be unauthenticated", e.Path, rt.BasePath)
		}
	}
	r := rt.Repos
	if len(r.List) == 0 || !(r.SyncIntervalS > 0) || !(r.GitTimeoutMS > 0) {
		return nil, errors.New("build.json runtime.repos needs list[], sync_interval_s and git_timeout_ms")
	}
	if !khRe.MatchString(r.KnownHosts) {
		return nil, errors.New("build.json runtime.repos.known_hosts must pin the github.com ed25519 host key")
	}
	seen := map[string]bool{}
	for _, x := range r.List {
		if !nameRe.MatchString(x.Name) || seen[x.Name] {
			return nil, fmt.Errorf("runtime.repos.list: bad or duplicate name %s", x.Name)
		}
		seen[x.Name] = true
		if !sshRe.MatchString(x.SSH) {
			return nil, fmt.Errorf("runtime.repos.list %s: ssh must be git@github.com:owner/repo.git (deploy-key transport only)", x.Name)
		}
		if !branchRe.MatchString(x.Branch) {
			return nil, fmt.Errorf("runtime.repos.list %s: bad branch", x.Name)
		}
		if !envRe.MatchString(x.KeyEnv) {
			return nil, fmt.Errorf("runtime.repos.list %s: key_env must be an env var name", x.Name)
		}
		// The vault holds credentials. It is never a served repo, whatever else is declared.
		if vaultRe.MatchString(x.Name) || vaultRe.MatchString(x.SSH) {
			return nil, fmt.Errorf("runtime.repos.list %s: a vault repo cannot be served", x.Name)
		}
	}
	for name, raw := range rt.Datasets {
		if strings.HasPrefix(name, "_") {
			continue
		}
		if !nameRe.MatchString(name) {
			return nil, fmt.Errorf("runtime.datasets: bad name %s", name)
		}
		var d dataset
		if err := json.Unmarshal(raw, &d); err != nil {
			return nil, fmt.Errorf("runtime.datasets.%s: not an object", name)
		}
		var probe map[string]json.RawMessage
		_ = json.Unmarshal(raw, &probe)
		if _, has := probe["builtin"]; has {
			if d.Builtin == nil || !builtRe.MatchString(*d.Builtin) {
				return nil, fmt.Errorf("runtime.datasets.%s: builtin must be data/<name>.json", name)
			}
			continue
		}
		if !seen[d.Repo] {
			return nil, fmt.Errorf("runtime.datasets.%s: repo %s is not declared in runtime.repos.list", name, d.Repo)
		}
		if !strings.HasSuffix(d.Path, ".json") {
			return nil, fmt.Errorf("runtime.datasets.%s: path must be a .json file", name)
		}
	}
	if ac := rt.Autocomplete; ac != nil {
		if !seen[ac.Repo] {
			return nil, fmt.Errorf("runtime.autocomplete: repo %s is not declared in runtime.repos.list", ac.Repo)
		}
		if !strings.HasSuffix(ac.Path, ".json") {
			return nil, errors.New("runtime.autocomplete: path must be a .json file")
		}
	} else {
		for _, e := range rt.Endpoints {
			if e.Path == rt.BasePath+"/autocomplete" {
				return nil, errors.New("runtime.endpoints declares /autocomplete but runtime.autocomplete names no file")
			}
		}
	}
	f := rt.Files
	if len(f.AllowedExt) == 0 || !(f.MaxBytes > 0) {
		return nil, errors.New("build.json runtime.files needs allowed_ext[], max_bytes, deny_path and deny_content")
	}
	for _, x := range f.AllowedExt {
		if !extRe.MatchString(x) {
			return nil, errors.New("build.json runtime.files needs allowed_ext[], max_bytes, deny_path and deny_content")
		}
	}
	if _, err := CompileJSRegexp(f.DenyPath, "i"); err != nil {
		return nil, err
	}
	if _, err := CompileJSRegexp(f.DenyContent, "im"); err != nil {
		return nil, err
	}
	s := rt.Authelia.Session
	if s == nil || !strings.HasPrefix(s.VerifyURL, "https://") || !pubRe.MatchString(s.PublicURL) || len(s.Users) == 0 || !(s.TimeoutMS > 0) {
		return nil, errors.New("build.json runtime.authelia.session needs verify_url, public_url (origin), users[] and timeout_ms")
	}
	c := rt.Cors
	if c == nil {
		return nil, errors.New("build.json runtime.cors needs https origins (no wildcard) and an optional .suffix")
	}
	for _, o := range c.Origins {
		if !originRe.MatchString(o) {
			return nil, errors.New("build.json runtime.cors needs https origins (no wildcard) and an optional .suffix")
		}
	}
	if c.OriginSuffix != nil && !suffixRe.MatchString(*c.OriginSuffix) {
		return nil, errors.New("build.json runtime.cors needs https origins (no wildcard) and an optional .suffix")
	}
	return &rt, nil
}

// CompileJSRegexp compiles a JavaScript RegExp source (flags i, m) with RE2. JS \s also matches Unicode spaces and
// the BOM, RE2's does not, so \s is widened to the JS set; every other construct the declared filters use (classes,
// \b, alternation, {n,m}, lazy-free quantifiers) means the same in both engines. A construct RE2 cannot express
// (lookaround, backreference) fails to compile and so refuses to start the service, never silently weakens the filter.
func CompileJSRegexp(src, flags string) (*regexp.Regexp, error) {
	const sp = `\s\p{Zs}\x{FEFF}\x{2028}\x{2029}`
	var b strings.Builder
	if strings.Contains(flags, "i") {
		b.WriteString("(?i)")
	}
	if strings.Contains(flags, "m") {
		b.WriteString("(?m)")
	}
	inClass := false
	for i := 0; i < len(src); i++ {
		ch := src[i]
		switch {
		case ch == '\\' && i+1 < len(src):
			n := src[i+1]
			i++
			switch {
			case n == 's' && inClass:
				b.WriteString(sp)
			case n == 's':
				b.WriteString("[" + sp + "]")
			case n == 'S' && !inClass:
				b.WriteString("[^" + sp + "]")
			default:
				b.WriteByte('\\')
				b.WriteByte(n)
			}
		case ch == '[' && !inClass:
			inClass = true
			b.WriteByte(ch)
		case ch == ']' && inClass:
			inClass = false
			b.WriteByte(ch)
		default:
			b.WriteByte(ch)
		}
	}
	return regexp.Compile(b.String())
}
